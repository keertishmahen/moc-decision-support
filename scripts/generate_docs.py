"""
scripts/generate_docs.py — regenerate the documents under docs/generated/.

    python scripts/generate_docs.py --api      # docs/generated/api-routes.md  (offline)
    python scripts/generate_docs.py --graph    # docs/generated/graph-schema.md (reads the live graph)
    python scripts/generate_docs.py --check    # exit 1 if api-routes.md is out of date (used by tests/CI)

Generated files are never edited by hand; tests/structure/test_docs.py fails if the API
document no longer matches the application.
"""
from __future__ import annotations

import argparse
import datetime
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
OUT = ROOT / "docs" / "generated"
HEADER = "<!-- GENERATED by scripts/generate_docs.py — do not edit by hand. -->\n"


def api_routes_markdown() -> str:
    from api.main import APP_VERSION, app

    rows = []
    for route in app.routes:
        path = getattr(route, "path", "")
        if not path.startswith("/api"):
            continue
        methods = sorted(m for m in (getattr(route, "methods", None) or []) if m not in {"HEAD", "OPTIONS"})
        doc = (getattr(route.endpoint, "__doc__", None) or "").strip().splitlines()
        summary = doc[0].strip() if doc else ""
        rows.append((path, ",".join(methods), route.endpoint.__module__, summary))
    rows.sort()
    lines = [HEADER, f"# API routes (v{APP_VERSION})", "",
             f"{len(rows)} routes. Source: `api/main.py` and `api/routes/`.", "",
             "| Method | Path | Defined in | Purpose |", "|---|---|---|---|"]
    for path, methods, module, summary in rows:
        lines.append(f"| {methods} | `{path}` | `{module}` | {summary} |")
    return "\n".join(lines) + "\n"


def graph_schema_markdown() -> str:
    from core.neo4j_client import Neo4jClient

    run = Neo4jClient()._run
    labels = run("MATCH (n) UNWIND labels(n) AS label RETURN label, count(*) AS n ORDER BY label")
    props = {r["label"]: sorted(r["keys"]) for r in run(
        "MATCH (n) UNWIND labels(n) AS label UNWIND keys(n) AS key RETURN label, collect(DISTINCT key) AS keys")}
    rels = run("MATCH (a)-[r]->(b) RETURN labels(a)[0] AS a, type(r) AS t, labels(b)[0] AS b, count(*) AS n ORDER BY t, a, b")
    rel_props = {r["t"]: sorted(r["keys"]) for r in run(
        "MATCH ()-[r]->() UNWIND keys(r) AS key RETURN type(r) AS t, collect(DISTINCT key) AS keys")}
    lines = [HEADER, "# Knowledge graph schema", "",
             f"Read from the live graph on {datetime.date.today().isoformat()}: "
             f"{sum(r['n'] for r in labels)} nodes, {sum(r['n'] for r in rels)} relationships.", "",
             "## Node labels", "", "| Label | Count | Properties |", "|---|---|---|"]
    for r in labels:
        keys = [k for k in props.get(r["label"], []) if k not in {"element_id"}]
        lines.append(f"| `{r['label']}` | {r['n']} | {', '.join(f'`{k}`' for k in keys)} |")
    lines += ["", "## Relationships", "", "| From | Type | To | Count | Properties |", "|---|---|---|---|---|"]
    for r in rels:
        lines.append(f"| `{r['a']}` | `{r['t']}` | `{r['b']}` | {r['n']} | {', '.join(f'`{k}`' for k in rel_props.get(r['t'], []))} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--api", action="store_true")
    parser.add_argument("--graph", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    if args.check:
        current = (OUT / "api-routes.md").read_text(encoding="utf-8") if (OUT / "api-routes.md").exists() else ""
        if current != api_routes_markdown():
            print("docs/generated/api-routes.md is out of date. Run: python scripts/generate_docs.py --api")
            return 1
        return 0
    if args.api:
        (OUT / "api-routes.md").write_text(api_routes_markdown(), encoding="utf-8", newline="\n")
        print("wrote docs/generated/api-routes.md")
    if args.graph:
        (OUT / "graph-schema.md").write_text(graph_schema_markdown(), encoding="utf-8", newline="\n")
        print("wrote docs/generated/graph-schema.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
