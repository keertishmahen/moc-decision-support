-- MoC platform Snowflake bootstrap (run as ACCOUNTADMIN)
-- Account: YOUR_SNOWFLAKE_ACCOUNT

USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS MOC_WH
  WITH WAREHOUSE_SIZE = 'X-SMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  COMMENT = 'MoC intelligence pipeline compute';

CREATE DATABASE IF NOT EXISTS MOC_DEV
  COMMENT = 'MoC platform medallion warehouse';

USE DATABASE MOC_DEV;

CREATE SCHEMA IF NOT EXISTS BRONZE COMMENT = 'dlt raw landing';
CREATE SCHEMA IF NOT EXISTS SILVER COMMENT = 'dbt staging and intermediate';
CREATE SCHEMA IF NOT EXISTS GOLD   COMMENT = 'dbt marts for Neo4j and ML';

ALTER USER YOUR_SNOWFLAKE_USER SET
  DEFAULT_WAREHOUSE = MOC_WH
  DEFAULT_NAMESPACE = MOC_DEV.BRONZE
  DEFAULT_ROLE = ACCOUNTADMIN;
