// ── Small pieces ──────────────────────────────────────────────────────────────
export function Chip({ tone, icon: Icon, children, title }: {
  tone: Token; icon?: LucideIcon; children: React.ReactNode; title?: string
}) {
  return (
    <span title={title} className="inline-flex items-center gap-1 rounded-full border px-2 py-0.5 text-[11px] font-semibold leading-tight"
      style={{ color: cssVar(tone), borderColor: tint(tone, 35), background: tint(tone, 10) }}>
      {Icon && <Icon className="h-3 w-3 shrink-0" strokeWidth={2} aria-hidden />}
      {children}
    </span>
  )
}

export const SourceChip = ({ kind, count }: { kind: SourceKind; count?: number }) => {
  const m = SOURCE_META[kind]
  return <Chip tone={m.tone} icon={m.icon} title={m.hint}>{m.label}{count !== undefined ? ` · ${count}` : ''}</Chip>
}

const BasisChip = ({ basis }: { basis: Basis }) => (
  <Chip tone={basis === 'llm' ? 'highlight' : basis === 'ml' ? 'node-risk' : 'slate'}>{BASIS_LABEL[basis]}</Chip>
)

export const StatusChip = ({ status }: { status: RunState }) => {
  const m = STATUS_META[status]
  return (
    <span className="inline-flex items-center gap-1 text-[11px] font-semibold" style={{ color: cssVar(m.tone) }}>
      <m.icon className={`h-3.5 w-3.5 ${status === 'running' ? 'animate-spin' : ''}`} strokeWidth={2} aria-hidden />
      {m.label}
    </span>
  )
}

