// ── Checkpoints ───────────────────────────────────────────────────────────────
export function CheckpointList({ checkpoints, names, checked, onToggle }: {
  checkpoints: Checkpoint[]; names: Record<string, string>; checked?: string[]; onToggle?: (id: string) => void
}) {
  if (!checkpoints.length) return <p className="text-sm text-white/50">No human checkpoints were raised.</p>
  return (
    <ul className="space-y-2">
      {checkpoints.map(cp => {
        const approval = cp.kind === 'approval'
        const tone: Token = approval ? 'accent2' : 'warn'
        const done = checked?.includes(cp.id)
        return (
          <li key={cp.id} className="rounded-xl border p-3" style={{ borderColor: tint(tone, 30), background: tint(tone, 6) }}>
            <div className="flex items-start gap-3">
              {onToggle ? (
                <input type="checkbox" checked={!!done} onChange={() => onToggle(cp.id)} aria-label={`Mark "${cp.what}" as done`}
                  className="mt-1 h-4 w-4 shrink-0 accent-[var(--color-accent)]" />
              ) : (
                (approval ? <Gavel className="mt-0.5 h-4 w-4 shrink-0" style={{ color: cssVar(tone) }} strokeWidth={1.75} aria-hidden />
                  : <ListChecks className="mt-0.5 h-4 w-4 shrink-0" style={{ color: cssVar(tone) }} strokeWidth={1.75} aria-hidden />)
              )}
              <div className="min-w-0 flex-1">
                <div className="flex flex-wrap items-center gap-2">
                  <span className={`text-sm font-semibold ${done ? 'text-white/45 line-through' : 'text-white/90'}`}>{cp.what}</span>
                  <Chip tone={tone}>{approval ? 'Approval' : 'Verification'}</Chip>
                </div>
                <div className="mt-1 text-xs text-white/55">{cp.why}</div>
                <div className="mt-1 text-[11px] text-white/40">
                  Who: <span className="text-white/70">{cp.role}</span> · raised by {names[cp.raised_by] ?? cp.raised_by}
                </div>
              </div>
            </div>
          </li>
        )
      })}
    </ul>
  )
}

// ── Why this recommendation? ──────────────────────────────────────────────────
type WhyTab = 'claims' | 'evidence' | 'agents' | 'gaps' | 'checks'

const CLAIMS_SHOWN = 8           // the rest behind "Show all" (all of them print)
const VERIFY_ORDER: Record<Verification, number> = { conflict: 0, unverified: 1, verified: 2, not_applicable: 3 }

/**
 * The trust and provenance panel. `focus` limits it to some agents (a section's "Why?");
 * conflicts are always shown because they need a person whichever section raised them.
 */
export function WhyPanel({ why, focus, title = 'Why this recommendation?', onClose }: {
  why: Provenance; focus?: string[]; title?: string; onClose?: () => void
}) {
  const [tab, setTab] = useState<WhyTab>('claims')
  const [allClaims, setAllClaims] = useState(false)
  const names = useMemo(() => Object.fromEntries(why.contributions.map(c => [c.agent, c.name])), [why])
  const evidenceById = useMemo(() => new Map(why.evidence.map(e => [e.id, e])), [why])

  const view = useMemo(() => {
    const inFocus = (agent: string) => !focus || focus.includes(agent)
    const findings = why.findings
      .filter(f => inFocus(f.agent) || f.verification === 'conflict')
      .sort((a, b) => VERIFY_ORDER[a.verification] - VERIFY_ORDER[b.verification])
    const cited = new Set(findings.flatMap(f => f.evidence))
    const evidence = focus ? why.evidence.filter(e => cited.has(e.id)) : why.evidence
    const grouped = new Map<SourceKind, Evidence[]>()
    for (const e of evidence) grouped.set(e.source, [...(grouped.get(e.source) ?? []), e])
    const citedBy = new Map<string, string[]>()
    for (const f of why.findings) for (const id of f.evidence) citedBy.set(id, [...(citedBy.get(id) ?? []), f.id])
    const gaps = (list: Gap[]) => list.filter(g => inFocus(g.agent))
    return {
      findings, grouped, citedBy,
      contributions: why.contributions.filter(c => inFocus(c.agent)),
      assumptions: gaps(why.assumptions), uncertainties: gaps(why.uncertainties), missing: gaps(why.missing),
      checkpoints: why.checkpoints.filter(c => !focus || focus.includes(c.raised_by)),
    }
  }, [why, focus])

  const nGaps = view.assumptions.length + view.uncertainties.length + view.missing.length
  const verified = view.findings.filter(f => f.verification === 'verified').length
  const conflicts = view.findings.filter(f => f.verification === 'conflict').length
  const tabs: { id: WhyTab; label: string; n: number }[] = [
    { id: 'claims', label: 'Claims', n: view.findings.length },
    { id: 'evidence', label: 'Evidence', n: [...view.grouped.values()].reduce((s, l) => s + l.length, 0) },
    { id: 'agents', label: 'Agents', n: view.contributions.length },
    { id: 'gaps', label: 'Gaps', n: nGaps },
    { id: 'checks', label: 'Human checks', n: view.checkpoints.length },
  ]

  return (
    <section className="moc-glass-card rounded-2xl p-4 space-y-3" aria-label={title}>
      <div className="flex flex-wrap items-start justify-between gap-2">
        <div>
          <div className="flex items-center gap-2 text-sm font-bold text-white">
            <CircleHelp className="h-4 w-4 text-accent" strokeWidth={2} aria-hidden />{title}
          </div>
          <div className="mt-1 text-xs text-white/50">
            {view.contributions.length} contributing {view.contributions.length === 1 ? 'agent' : 'agents'} · {verified} verified
            {conflicts ? <> · <span style={{ color: cssVar('danger') }}>{conflicts} {conflicts === 1 ? 'conflict' : 'conflicts'}</span></> : ' · no conflicts'}
            {' '}· {nGaps} open {nGaps === 1 ? 'gap' : 'gaps'} · {view.checkpoints.length} human {view.checkpoints.length === 1 ? 'checkpoint' : 'checkpoints'}
          </div>
        </div>
        {onClose && (
          <button type="button" onClick={onClose} className="no-print rounded-lg p-1 text-white/40 hover:text-white/80" aria-label="Close">
            <X className="h-4 w-4" strokeWidth={2} />
          </button>
        )}
      </div>

      <div>
        <div className={`${LABEL} mb-1.5`}>Where the knowledge comes from</div>
        <div className="flex flex-wrap gap-1.5">
          {[...view.grouped.entries()].map(([kind, list]) => <SourceChip key={kind} kind={kind} count={list.length} />)}
        </div>
      </div>

      <div className="no-print flex flex-wrap gap-1.5" role="tablist" aria-label="Provenance">
        {tabs.map(t => (
          <button key={t.id} type="button" role="tab" aria-selected={tab === t.id} onClick={() => setTab(t.id)}
            className={`rounded-xl px-3 py-1.5 text-xs font-semibold transition-colors ${tab === t.id ? 'bg-accent/20 text-white border border-accent/50' : 'border border-white/10 text-white/50 hover:text-white/80'}`}>
            {t.label} <span className="text-white/40">{t.n}</span>
          </button>
        ))}
      </div>

      {tab === 'claims' && (
        <ul className="space-y-2">
          {view.findings.map((f, i) => (
            <FindingRow key={f.id} f={f} names={names} evidence={evidenceById}
              hidden={!allClaims && i >= CLAIMS_SHOWN} />
          ))}
          {!view.findings.length && <li className="text-sm text-white/50">No findings recorded.</li>}
          {view.findings.length > CLAIMS_SHOWN && (
            <li className="no-print">
              <button type="button" onClick={() => setAllClaims(a => !a)} className="text-xs font-semibold text-accent hover:text-accent-soft">
                {allClaims ? 'Show fewer' : `Show all ${view.findings.length} claims (conflicts and unverified claims are listed first)`}
              </button>
            </li>
          )}
        </ul>
      )}

      {tab === 'evidence' && (
        <div className="space-y-3">
          {[...view.grouped.entries()].map(([kind, list]) => {
            const m = SOURCE_META[kind]
            return (
              <div key={kind}>
                <div className="mb-1 flex items-center gap-2">
                  <m.icon className="h-4 w-4" style={{ color: cssVar(m.tone) }} strokeWidth={1.75} aria-hidden />
                  <span className="text-sm font-semibold text-white/85">{m.label}</span>
                  <span className="text-[11px] text-white/40">{m.hint}</span>
                </div>
                <ul className="divide-y divide-white/5 rounded-xl border border-white/8">
                  {list.map(e => (
                    <li key={e.id} className="px-3 py-2 text-xs">
                      <div className="flex flex-wrap items-baseline justify-between gap-2">
                        <span className="font-semibold text-white/85">{e.label}</span>
                        <span className="font-mono text-[10px] text-white/35">{e.reference}</span>
                      </div>
                      {e.detail && <div className="mt-0.5 text-white/50">{e.detail}</div>}
                      {view.citedBy.get(e.id) && <div className="mt-0.5 text-[10px] text-white/30">Supports {view.citedBy.get(e.id)!.join(', ')}</div>}
                    </li>
                  ))}
                </ul>
              </div>
            )
          })}
        </div>
      )}

      {tab === 'agents' && (
        <ul className="grid grid-cols-1 lg:grid-cols-2 gap-2">
          {view.contributions.map(c => (
            <li key={c.agent} className="rounded-xl border border-white/8 p-3 space-y-1.5">
              <div className="flex items-start justify-between gap-2">
                <span className="text-sm font-semibold text-white/90">{c.name}</span>
                <StatusChip status={c.status} />
              </div>
              <div className="text-xs text-white/60">{c.role}</div>
              <div className="flex flex-wrap gap-1"><BasisChip basis={c.basis} />{c.sources.map(s => <SourceChip key={s} kind={s} />)}</div>
              {c.summary && <div className="text-xs text-white/75">{c.summary}</div>}
              <div className="font-mono text-[10px] text-white/35 break-words">Reuses {c.components.join(' · ')}</div>
              {c.error && <div className="text-[11px]" style={{ color: cssVar('danger') }}>Error: {c.error}</div>}
            </li>
          ))}
        </ul>
      )}

      {tab === 'gaps' && (
        <div className="grid grid-cols-1 lg:grid-cols-3 gap-3">
          <GapList title="Assumptions" icon={CircleDashed} tone="warn" items={view.assumptions} names={names} />
          <GapList title="Uncertainties" icon={CircleHelp} tone="highlight" items={view.uncertainties} names={names} />
          <GapList title="Missing information" icon={CircleX} tone="danger" items={view.missing} names={names} />
        </div>
      )}

      {tab === 'checks' && <CheckpointList checkpoints={view.checkpoints} names={names} />}

      <p className="text-[11px] text-white/35 leading-relaxed">
        The Verification agent checks named equipment, P&amp;ID tags, HAZOP/PSSR answers and the risk rating against the
        knowledge graph and similar past changes. It does not judge the meaning of free text, so read language-model claims yourself.
        A recommendation is advice; the organisation&apos;s approver decides.
      </p>
    </section>
  )
}

function FindingRow({ f, names, evidence, hidden = false }: {
  f: Finding; names: Record<string, string>; evidence: Map<string, Evidence>; hidden?: boolean
}) {
  const v = VERIFY_META[f.verification]
  return (
    <li className={`rounded-xl border p-3 ${hidden ? 'hidden print:block' : ''}`} style={{ borderColor: tint(v.tone, f.verification === 'conflict' ? 45 : 18) }}>
      <div className="flex items-start gap-2.5">
        <v.icon className="mt-0.5 h-4 w-4 shrink-0" style={{ color: cssVar(v.tone) }} strokeWidth={2} aria-label={v.label} />
        <div className="min-w-0 flex-1 space-y-1">
          <div className="text-sm text-white/85">{f.statement}</div>
          <div className="flex flex-wrap items-center gap-1.5 text-[11px] text-white/45">
            <span className="font-mono text-white/30">{f.id}</span>
            <span>{names[f.agent] ?? f.agent}</span>
            <BasisChip basis={f.basis} />
            <Chip tone={v.tone}>{v.label}</Chip>
            {f.confidence && <span>confidence {f.confidence}</span>}
          </div>
          {f.note && <div className="text-[11px] text-white/50">{f.note}</div>}
          {f.evidence.length > 0 && (
            <div className="flex flex-wrap gap-1">
              {f.evidence.map(id => {
                const e = evidence.get(id)
                if (!e) return null
                const m = SOURCE_META[e.source]
                return <Chip key={id} tone={m.tone} icon={m.icon} title={`${m.label}: ${e.reference}${e.detail ? ` (${e.detail})` : ''}`}>{e.label}</Chip>
              })}
            </div>
          )}
        </div>
      </div>
    </li>
  )
}

function GapList({ title, icon: Icon, tone, items, names }: {
  title: string; icon: LucideIcon; tone: Token; items: Gap[]; names: Record<string, string>
}) {
  return (
    <div className="rounded-xl border border-white/8 p-3">
      <div className="mb-2 flex items-center gap-1.5 text-sm font-semibold text-white/85">
        <Icon className="h-4 w-4" style={{ color: cssVar(tone) }} strokeWidth={1.75} aria-hidden />{title}
        <span className="text-white/40 font-normal">{items.length}</span>
      </div>
      {items.length === 0 ? <p className="text-xs text-white/40">None recorded.</p> : (
        <ul className="space-y-1.5">
          {items.map((g, i) => (
            <li key={`${g.agent}-${i}`} className="text-xs text-white/70">
              {g.text} <span className="text-white/35">({names[g.agent] ?? g.agent})</span>
            </li>
          ))}
        </ul>
      )}
    </div>
  )
}

// ── "Why?" toggle for one section ─────────────────────────────────────────────
export function WhyToggle({ why, focus, label, button = 'Why?', large = false }: {
  why: Provenance; focus?: string[]; label: string; button?: string; large?: boolean
}) {
  const [open, setOpen] = useState(false)
  return (
    <div className="space-y-2">
      <button type="button" onClick={() => setOpen(o => !o)} aria-expanded={open}
        className={`no-print inline-flex items-center gap-1 font-semibold text-accent hover:text-accent-soft ${large ? 'text-sm' : 'text-xs'}`}>
        <CircleHelp className={large ? 'h-4 w-4' : 'h-3.5 w-3.5'} strokeWidth={2} aria-hidden />
        {open ? 'Hide' : button}
      </button>
      {open && <WhyPanel why={why} focus={focus} title={label} onClose={() => setOpen(false)} />}
    </div>
  )
}

