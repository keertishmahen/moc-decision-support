  waiting:  { label: 'Waiting', tone: 'slate' },
  running:  { label: 'Analyzing…', tone: 'accent' },
  ok:       { label: 'Complete', tone: 'ok' },
  degraded: { label: 'Partial result', tone: 'warn' },
  failed:   { label: 'Failed', tone: 'danger' },
  skipped:  { label: 'Skipped', tone: 'slate' },
